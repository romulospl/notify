#!/bin/sh
# Generates the distribution code (collector/cmd/stellytics-collector) with the OCB.
#
# The OCB always creates its own go.mod in the output folder. Since ADR 0002
# asks for a single Go module in services/, the script generates into a
# temporary folder and copies only the .go files, which compile inside the
# services module. Run it from inside services/ after changing
# collector/builder-config.yaml or the OCB version; CI checks that the result
# is committed.
set -eu

OCB_VERSION=v0.164.0
out=collector/cmd/stellytics-collector
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

sed "s|output_path: .*|output_path: $tmp|" collector/builder-config.yaml > "$tmp/builder-config.yaml"
go run "go.opentelemetry.io/collector/cmd/builder@$OCB_VERSION" \
  --config "$tmp/builder-config.yaml" --skip-compilation --skip-get-modules >/dev/null

mkdir -p "$out"
rm -f "$out"/*.go
for f in "$tmp"/*.go; do
  { echo "// Code generated by the OCB ($OCB_VERSION) from collector/builder-config.yaml. Do not edit: run collector/generate.sh."; echo; cat "$f"; } > "$out/$(basename "$f")"
done
gofmt -w "$out"
